function bandeira(iso) {
  return iso
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
}

const seen = new Set();
const list = paises
  .filter(([iso]) => {
    if (seen.has(iso)) return false;
    seen.add(iso);
    return true;
  })
  .sort((a, b) => a[1].localeCompare(b[1], "pt"));

const lines = [
  "export type PaisTelefone = {",
  "  iso: string;",
  "  nome: string;",
  "  dial: string;",
  "  bandeira: string;",
  "};",
  "",
  "export function bandeiraPais(iso: string): string {",
  "  return iso",
  "    .toUpperCase()",
  "    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));",
  "}",
  "",
  "export const PAISES_TELEFONE: PaisTelefone[] = [",
  ...list.map(
    ([iso, nome, dial]) =>
      `  { iso: "${iso}", nome: "${nome}", dial: "+${dial}", bandeira: "${bandeira(iso)}" },`
  ),
  "];",
  "",
  "export function paisPorIso(iso: string): PaisTelefone | undefined {",
  "  return PAISES_TELEFONE.find((p) => p.iso === iso);",
  "}",
  "",
  "export function paisPorDial(dial: string): PaisTelefone | undefined {",
  "  return PAISES_TELEFONE.find((p) => p.dial === dial);",
  "}",
  "",
];

writeFileSync("src/lib/paises-telefone.ts", lines.join("\n"), "utf8");
