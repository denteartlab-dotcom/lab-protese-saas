const ptMatch = c.match(/export const messagesPrintPt = \{([\s\S]*?)\} as const;/);
if (!ptMatch) throw new Error("messagesPrintPt not found");
const ptBody = ptMatch[1];
const keys = [...ptBody.matchAll(/"([^"]+)":/g)].map((m) => m[1]);

function buildBlock(name, overrides) {
  const lines = keys.map((key) => {
    const val = overrides[key] ?? enOverrides[key] ?? key;
    const escaped = val.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    return `  "${key}": "${escaped}",`;
  });
  return `export const ${name}: Record<keyof typeof messagesPrintPt, string> = {\n${lines.join("\n")}\n};`;
}

c = c.replace(
  /export const messagesPrintEn:[\s\S]*?export const messagesPrintEs:[\s\S]*?};/,
  `${buildBlock("messagesPrintEn", enOverrides)}\n\n${buildBlock("messagesPrintEs", esOverrides)};`
);

fs.writeFileSync(file, c);
console.log(`Synced ${keys.length} keys to EN and ES`);
