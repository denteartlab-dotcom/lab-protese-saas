function aplicarSubs(texto: string, subs: Sub[]): string {
  let s = texto;
  for (const [re, rep] of subs) s = s.replace(re, rep);
  return s;
}

/** Traduz texto PT para EN por substituição lexical (fallback). */
export function paraEn(pt: string): string {
  return aplicarSubs(pt, SUB_EN);
}

/** Traduz texto PT para ES por substituição lexical (fallback). */
export function paraEs(pt: string): string {
  return aplicarSubs(pt, SUB_ES);
}

/** Texto parece interface em português (não traduzir nomes próprios sem acentos). */
export function pareceTextoUiPortugues(texto: string): boolean {
  const s = texto.trim();
  if (!s || s.length > 220) return false;
  if (/[àáâãéêíóôõúçÀÁÂÃÉÊÍÓÔÕÚÇ]/.test(s)) return true;
  return /\b(não|nao|ao|dos|das|para|com|sem|buscar|salvar|cancelar|excluir|editar|novo|carregando|informe|selecione|todos|todas|relatório|relatorio|configurações|configuracoes|usuário|usuario|senha|permissão|permissao|paciente|cliente|serviço|servico|produção|producao|financeiro|estoque|cadastro|orçamento|orcamento|entrega|comissão|comissao|imprimir|exportar|importar|filtro|período|periodo|situação|situacao|vencimento|receita|despesa|boleto|fatura|conta|saldo|extrato|etapa|setor|colaborador|fornecedor|entregador|prestador|laboratório|laboratorio|próximo|proximo|anterior|confirmar|fechar|abrir|enviar|remover|aplicar|detalhes|resumo|desconto|parcela|vencido|pago|aberto|sincronizar|modelo|padrão|padrao|obrigatório|obrigatorio|opcional|erro|sucesso|atenção|atencao|copiar|download|upload|visualizar|descrição|descricao|observação|observacao|endereço|endereco|telefone|cidade|bairro|quantidade|valor|nome|tipo|data|hora|mês|mes|ano|dia|semana|hoje|ontem|amanhã|amanha)\b/i.test(
    s
  );
}

/** Se EN/ES do catálogo ainda é igual ao PT, aplica fallback lexical. */
export function aplicarFallbackTraducao(
  locale: Locale,
  textoPt: string | undefined,
  textoAtual: string
): string {
  if (locale === "pt" || !textoPt) return textoAtual;
  if (textoAtual !== textoPt) return textoAtual;
  return locale === "en" ? paraEn(textoPt) : paraEs(textoPt);
}

/** Fallback para string solta fora do catálogo (I18nAuto). */
export function traduzirTextoUiLivre(locale: Locale, texto: string): string {
  if (locale === "pt" || !pareceTextoUiPortugues(texto)) return texto;
  const traduzido = locale === "en" ? paraEn(texto) : paraEs(texto);
  return traduzido !== texto ? traduzido : texto;
}
